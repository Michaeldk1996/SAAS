'use strict';
/**
 * TEN-318 (TEN-312 N12) — the committed floor for TIEBREAK POINT ROWS.
 *
 * WHY THIS EXISTS
 * ---------------
 * api-tennis stops returning a match's tiebreak points some time after it is played.
 * Asked again, it sends the tennis games plus a ONE-ROW set summary
 * (`score "7 - 6"`, one blank point) and no point rows. That held for 4 of 4 re-asked
 * matches on 2026-09-28, over both `match_key=` and the player-window fetch. Matches
 * finished the same day still carry them (8/32 and 4/9 TB sets on 09-27 and 09-28).
 * So the point rows we already hold cannot be fetched again. point-by-point-cache.json
 * held the only copy, and it lives ONLY in the Actions cache
 * (`bsp-caches-v<schema>-<day>`). The tracked copy is a 52-entry fossil from Task 4.
 *
 * THE FAILURE MODE THIS PREVENTS, AND IT HAS ALREADY HAPPENED ONCE
 * ----------------------------------------------------------------
 * The Actions cache key carries PROFILE_SCHEMA_VERSION, and so do its restore-keys
 * (TEN-243). A schema bump is therefore a GUARANTEED cache miss. Run 4067
 * (2026-09-21 02:01Z) logged
 *   `Cache not found for input keys: bsp-caches-v15-2026-09-21, bsp-caches-v15-`
 * and build-point-by-point.js rebuilt from the fossil. It got away with that only
 * because the feed still carried tiebreak points then. The next schema bump, or an
 * LRU eviction at the repo's 10 GiB cache ceiling, would refetch every match, get
 * the one-row summary back, and publish pbp/ shards with the tiebreak sections gone.
 * The loss would be permanent.
 *
 * THE MECHANISM: a committed, merge-only floor.
 *   - absorb():  every run folds every TB row the cache holds into the floor, BEFORE
 *                any fetch can replace an entry and again after the fetches.
 *   - restore(): every run writes the floor's rows back into any cache entry that has
 *                a log but lacks them. A refetch that returns fewer TB points cannot
 *                shrink the entry, and a from-scratch rebuild gets its TB points back
 *                the moment it holds the match's log again.
 *   - assertSuperset(): the floor is never written unless it still holds every row it
 *                was loaded with. An unreadable floor is never overwritten.
 * Committed back at most once a UTC hour, and only when rows were added, by
 * pipeline.yml ("Refresh the committed tiebreak floor"). So the durable copy is git,
 * not the Actions cache or the live site. The Actions cache saves only on a day's
 * first run, and the feed can drop a fresh match's rows within the day.
 *
 * WHAT COUNTS AS A TIEBREAK ROW is the dashboard's own rule (`pbpSplitSet`,
 * bsp-consult-dashboard.html): a game row with an EMPTY points list and an integer
 * running score "a - b", in a set holding at least 3 of them. It must be the same
 * rule. The floor protects exactly what the page renders as "Tiebreak · Set N".
 *
 * FORMAT (plain minified JSON, like historical-match-stats.floor.json, so git can
 * delta a daily append):
 *   { "<eventKey>": { "<setNo>": [[g, server, winner, "a - b"], ...] } }
 * server/winner: 1 = p1, 2 = p2, 0 = null (api-tennis First/Second Player, the same
 * orientation the cache entry stores). Rows are sorted by a+b (play order), and event
 * keys enumerate ascending, so an idle run re-serialises byte-for-byte.
 *
 * Regenerated by: build-point-by-point.js (every pipeline run), committed back by
 * pipeline.yml. Never hand-edit it.
 */
const fs = require('fs');

const FLOOR_PATH = 'pbp-tiebreak-floor.json';
const MIN_TB_ROWS = 3;   // pbpSplitSet: "only treat as a tiebreak when there's a real sequence"
const TENNIS_POINT = /15|30|40|A/;

function parseScore(sc) {
  const m = /^(\d+)\s*-\s*(\d+)$/.exec(String(sc || '').trim());
  return m ? [+m[1], +m[2]] : null;
}
const enc = s => (s === 'p1' ? 1 : s === 'p2' ? 2 : 0);
// Row identity is (point number, running score), counted as a MULTISET. Measured over
// the 11,198 stored TB sets (2026-09-28): 669 rows in 248 sets repeat a running score,
// 364 of them (212 sets) under a different point number and 305 (36 sets) repeating
// BOTH (the feed doubled the sequence). The page renders every one of them, so "never drop a stored row" has
// to keep every copy: 131,753 rows, not 131,084. server/winner are deliberately NOT in
// the key: a refetch that returns the same point with other fields must not render it
// twice. The cache keeps the fetched version and the floor keeps its own.
const rowKey = r => `${r[0] ?? ''}|${String(r[3]).replace(/\s+/g, '')}`;
const encRow = g => [g.g ?? null, enc(g.server), enc(g.winner), g.score];
function tally(rows) {
  const m = new Map();
  for (const r of rows) m.set(rowKey(r), (m.get(rowKey(r)) || 0) + 1);
  return m;
}
const dec = n => (n === 1 ? 'p1' : n === 2 ? 'p2' : null);
const playOrder = (x, y) => {
  const a = parseScore(x[3]), b = parseScore(y[3]);
  return (a[0] + a[1]) - (b[0] + b[1]) || a[0] - b[0] || (x[0] ?? 0) - (y[0] ?? 0);
};

function isTiebreakRow(g) {
  if (!g) return false;
  const pts = Array.isArray(g.points) ? g.points : [];
  if (pts.some(p => TENNIS_POINT.test((p && p.s) || ''))) return false;   // a real game
  return pts.length === 0 && !!parseScore(g.score);                         // not the one-row summary
}

// { setNo: [[g, server, winner, score], ...] } for one entry's sets. Sets below the
// 3-row threshold are not tiebreaks and are not returned.
function extractTiebreaks(sets) {
  const out = {};
  for (const s of (Array.isArray(sets) ? sets : [])) {
    if (!s || !Array.isArray(s.games)) continue;
    const rows = s.games.filter(isTiebreakRow).map(encRow);
    if (rows.length >= MIN_TB_ROWS) out[s.set] = rows.sort(playOrder);
  }
  return out;
}

// Fold every TB row held in `cache` into `floor` (mutated). A multiset union: each
// distinct row ends up as many times as the larger side holds it, and a row already in
// the floor is never replaced or removed. Returns the number of rows added.
function absorb(floor, cache) {
  let added = 0;
  for (const ek of Object.keys(cache || {})) {
    const e = cache[ek];
    if (!e || !Array.isArray(e.sets) || !e.sets.length) continue;
    for (const [setNo, rows] of Object.entries(extractTiebreaks(e.sets))) {
      const have = ((floor[ek] ||= {})[setNo] ||= []);
      const hold = tally(have);
      for (const r of rows) {
        const k = rowKey(r), n = hold.get(k) || 0;
        if (n > 0) { hold.set(k, n - 1); continue; }   // matched by a row the floor holds
        have.push(r); added++;
      }
      have.sort(playOrder);
    }
  }
  return added;
}

// Write the floor's TB rows back into every cache entry that holds a log but is
// missing some of them. IN PLACE (set.games / entry.sets are pushed to, never
// replaced), so point-by-point.json, which shares these arrays, gets them too. An
// entry with no log (absent, or a cached negative) is left alone; the floor keeps
// its rows until the match's log is held again. Returns { entries, rows } restored.
function restore(cache, floor) {
  let entries = 0, rows = 0;
  for (const ek of Object.keys(floor || {})) {
    const e = cache && cache[ek];
    if (!e || !Array.isArray(e.sets) || !e.sets.length) continue;
    let touched = false;
    for (const [setNo, frows] of Object.entries(floor[ek])) {
      let s = e.sets.find(x => x && String(x.set) === String(setNo));
      if (!s) { s = { set: Number(setNo), games: [] }; e.sets.push(s); e.sets.sort((a, b) => a.set - b.set); }
      if (!Array.isArray(s.games)) s.games = [];
      const hold = tally(s.games.filter(isTiebreakRow).map(encRow));
      for (const r of frows) {
        const k = rowKey(r), n = hold.get(k) || 0;
        if (n > 0) { hold.set(k, n - 1); continue; }
        s.games.push({ g: r[0], server: dec(r[1]), winner: dec(r[2]), score: r[3], points: [] });
        rows++; touched = true;
      }
    }
    if (touched) entries++;
  }
  return { entries, rows };
}

function census(floor) {
  let matches = 0, sets = 0, rows = 0;
  for (const ek of Object.keys(floor || {})) {
    matches++;
    for (const r of Object.values(floor[ek])) { sets++; rows += r.length; }
  }
  return { matches, sets, rows };
}

// Throws unless `next` holds every row of every (eventKey, set) that `prev` held, at
// least as many times.
function assertSuperset(prev, next) {
  for (const ek of Object.keys(prev || {})) {
    for (const [setNo, rows] of Object.entries(prev[ek])) {
      const hold = tally((((next || {})[ek] || {})[setNo]) || []);
      const lost = rows.filter(r => { const k = rowKey(r), n = hold.get(k) || 0; hold.set(k, n - 1); return n <= 0; });
      if (lost.length) throw new Error(`tiebreak floor would drop ${lost.length} row(s) of ${ek} set ${setNo} - refusing to write it`);
    }
  }
}

// { floor, status }. 'absent' starts an empty floor (a local first run). 'unreadable'
// returns floor null: the caller must NOT write it, because the only thing it could
// write is less than the file it failed to read.
function loadFloor(path = FLOOR_PATH) {
  if (!fs.existsSync(path)) return { floor: {}, status: 'absent' };
  try {
    const f = JSON.parse(fs.readFileSync(path, 'utf8'));
    if (!f || typeof f !== 'object' || Array.isArray(f)) throw new Error('not an object');
    return { floor: f, status: 'ok' };
  } catch (e) {
    return { floor: null, status: 'unreadable', error: e.message };
  }
}

const serialize = floor => JSON.stringify(floor);
const clone = floor => JSON.parse(JSON.stringify(floor));

module.exports = {
  FLOOR_PATH, MIN_TB_ROWS, isTiebreakRow, extractTiebreaks, absorb, restore, census,
  assertSuperset, loadFloor, serialize, clone, rowKey,
};
