#!/usr/bin/env node
// tools/mto-levels.sql = the site's own tournament table (TOURNAMENT_CATALOG in bsp-consult-dashboard.html) as rows of
// mto.tournament_level, so the MTO alert's level badge is the level the site prints. Generated, never hand-edited:
//   node tools/mto-levels.mjs          writes the file
//   node tools/mto-levels.mjs --check  exits 1 when the file is out of step with the page (npm test)
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(ROOT, 'bsp-consult-dashboard.html'), 'utf8');
const a = html.indexOf('const TOURNAMENT_CATALOG = [');
if (a < 0) { console.error('TOURNAMENT_CATALOG not found'); process.exit(1); }
const b = html.indexOf('\n];', a);
const catalog = new Function('return ' + html.slice(html.indexOf('[', a), b + 2))();
const rows = new Map(), ctry = new Map();
for (const t of catalog) {
  if (!t || !t.name || !t.category) continue;
  const k = String(t.name).trim().toLowerCase();
  if (rows.has(k) && rows.get(k) !== t.category) { console.error('two levels for', t.name); process.exit(1); }
  rows.set(k, t.category);
  if (/^[A-Z]{2}$/.test(t.country || '') && !ctry.has(k)) ctry.set(k, t.country);
}
if (rows.size < 50) { console.error('only', rows.size, 'tournaments read'); process.exit(1); }
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const sql = '-- GENERATED by tools/mto-levels.mjs from TOURNAMENT_CATALOG (bsp-consult-dashboard.html). Do not edit by hand.\n' +
  'delete from mto.tournament_level;\ninsert into mto.tournament_level (name_key, level, country) values\n' +
  [...rows].sort((x, y) => x[0] < y[0] ? -1 : 1).map(([k, v]) => `  (${q(k)}, ${q(v)}, ${ctry.has(k) ? q(ctry.get(k)) : 'null'})`).join(',\n') + ';\n';
const out = path.join(ROOT, 'tools', 'mto-levels.sql');
if (process.argv.includes('--check')) {
  const have = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (have !== sql) { console.error('FAIL  tools/mto-levels.sql is out of step with TOURNAMENT_CATALOG: run node tools/mto-levels.mjs'); process.exit(1); }
  console.log(`PASS  mto-levels: ${rows.size} tournaments, in step with the page`); process.exit(0);
}
fs.writeFileSync(out + '.tmp', sql); fs.renameSync(out + '.tmp', out); console.log('wrote', rows.size, 'tournaments');
